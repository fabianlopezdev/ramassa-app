import { readFile } from 'node:fs/promises';
import { describe, expect, test } from 'bun:test';

const readSource = (path: string) => readFile(path, 'utf8');

describe('accessibility CI local service contract', () => {
  test('the browser gate consumes the public key generated by its local Supabase runtime', async () => {
    const [workflow, playwrightConfig, session] = await Promise.all([
      readSource('.github/workflows/ci.yml'),
      readSource('playwright.config.ts'),
      readSource('scripts/qa-web/session.ts'),
    ]);

    expect(workflow).toContain('EXPO_PUBLIC_SUPABASE_ANON_KEY');
    expect(workflow).toContain('supabase@2.90.0 status -o env');
    expect(workflow.match(/supabase@2\.90\.0/g)).toHaveLength(3);
    expect(playwrightConfig).toContain('process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY');
    expect(session).toContain('process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY');
  });

  test('pull requests run only the quality gates; the browser gate runs on main and on demand', async () => {
    const workflow = await readSource('.github/workflows/ci.yml');
    const accessibilityJob = workflow.slice(workflow.indexOf('  accessibility-web:'));

    expect(workflow).toContain('workflow_dispatch:');
    expect(workflow).toMatch(/push:\n\s+branches: \[main\]/);
    expect(accessibilityJob).toContain("if: github.event_name != 'pull_request'");
    expect(workflow.slice(0, workflow.indexOf('  accessibility-web:'))).not.toContain(
      'github.event_name',
    );
  });

  test('the browser gate owns frame naming without auditing third-party frame internals', async () => {
    const accessibilityGate = await readSource('scripts/qa-web/accessibility.web-qa.ts');

    expect(accessibilityGate).toContain("exclude('iframe')");
    expect(accessibilityGate).toContain("toHaveAttribute('title', /\\S+/)");
  });
});
