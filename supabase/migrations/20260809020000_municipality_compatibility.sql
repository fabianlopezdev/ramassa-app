-- Repair mechanically equivalent historical values before enforcing new
-- writes. This deliberately does not guess aliases such as Vich -> Vic.
update public.profiles as profile
set city = municipality.canonical
from public.municipality_catalog as municipality
where profile.city is not null
  and lower(btrim(profile.city)) = lower(municipality.canonical)
  and profile.city is distinct from municipality.canonical;

-- NOT VALID is the compatibility mechanism: all future inserts and city
-- changes are checked immediately, while an unknown pre-migration value does
-- not abort deployment. Such rows are visible in the service-role-only report
-- below and can be corrected to a canonical value before validating the FK.
alter table public.profiles
  add constraint profiles_city_municipality_canonical_fkey
  foreign key (city)
  references public.municipality_catalog (canonical)
  not valid;

create view public.municipality_compatibility_report
with (security_invoker = true)
as
select
  profile.city as legacy_value,
  count(*)::bigint as profile_count
from public.profiles as profile
left join public.municipality_catalog as municipality
  on municipality.canonical = profile.city
where profile.city is not null
  and municipality.code is null
group by profile.city;

comment on view public.municipality_compatibility_report is
  'Unresolved pre-RAPP-100 profiles.city buckets. Resolve each to municipality_catalog.canonical, then validate profiles_city_municipality_canonical_fkey.';

revoke all on table public.municipality_compatibility_report from anon, authenticated;
grant select on table public.municipality_compatibility_report to service_role;
