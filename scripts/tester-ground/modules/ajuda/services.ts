export interface ServiceCategorySeed {
  readonly slug: string;
  readonly name: Translated;
  readonly icon: string;
  readonly color: string;
  readonly sortOrder: number;
  /** The product's field definitions with French labels added. */
  readonly metadataSchema: { readonly fields: readonly unknown[] };
}

function seedCategory(definition: ServiceCategoryDefinition): ServiceCategorySeed {
  const color = CATEGORY_COLORS[definition.slug];
  const frenchName = FRENCH_CATEGORY_NAMES[definition.slug];
  if (color === undefined || frenchName === undefined) {
    throw new Error(`No colour or French name for service category ${definition.slug}`);
  }
  return {
    slug: definition.slug,
    name: { ...definition.name, fr: frenchName },
    icon: definition.icon,
    color,
    sortOrder: definition.sortOrder,
    metadataSchema: {
      fields: definition.fields.map((field) => ({
        ...field,
        label: { ...field.label, fr: FRENCH_FIELD_LABELS[field.key] ?? field.label.en },
      })),
    },
  };
}

